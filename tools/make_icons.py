"""make_icons -- generate neoui's icon set (original artwork) into ui/icons/.

    python3 tools/make_icons.py

One visual language, written here once so the whole set can be restyled in one place:
- glyphs live on a 24-unit grid, drawn as strokes of one weight with round caps and joins;
- ui/icons/sys/<name>.svg: a white glyph (Slint tints it with `colorize`), rasterised at 96 px;
- ui/icons/apps/<name>.svg: the glyph in white on a rounded tile with a soft top-lit gradient, rasterised at 192 px.
Slint renders each SVG at build time at its width/height (crates/neoui-render/build.rs embeds them).
"""

