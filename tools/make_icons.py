def digit_svg(ch: str) -> str:
    w = 6 if ch == ":" else 14
    if ch == ":":
        body = '<circle cx="3" cy="8.4" r="1.5" fill="#ffffff"/><circle cx="3" cy="17.2" r="1.5" fill="#ffffff"/>'
    else:
        GLYPHS["_d"] = DIGITS[ch]
        body = shapes("_d", "#ffffff")
        del GLYPHS["_d"]
    return (HEAD + f'<svg xmlns="http://www.w3.org/2000/svg" width="{w * 10}" height="240" viewBox="0 0 {w} 24">'
            f'<g stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">{body}</g></svg>\n')


def main() -> None:
    os.makedirs(os.path.join(OUT, "digits"), exist_ok=True)
    for ch in [*DIGITS, ":"]:
        with open(os.path.join(OUT, "digits", ("colon" if ch == ":" else "d" + ch) + ".svg"), "w") as f:
            f.write(digit_svg(ch))
    for sub in ("sys", "apps"):
        os.makedirs(os.path.join(OUT, sub), exist_ok=True)
    for name in GLYPHS:
        if name in APPS:
            continue
        with open(os.path.join(OUT, "sys", name + ".svg"), "w") as f:
            f.write(sys_svg(name))
    for name, base in APPS.items():
        with open(os.path.join(OUT, "apps", name + ".svg"), "w") as f:
            f.write(app_svg(name, base))
    print(
        f"make_icons: {len(APPS)} app icons, {len(GLYPHS) - len(APPS)} system icons -> {os.path.normpath(OUT)}"
    )


if __name__ == "__main__":
    main()
