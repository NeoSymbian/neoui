def gear(teeth=8, r_out=8.6, r_in=6.6, w=0.42) -> str:
    pts = []
    for i in range(teeth):
        a = 2 * math.pi * i / teeth
        for da, r in ((-w, r_in), (-w * 0.55, r_out), (w * 0.55, r_out), (w, r_in)):
            pts.append((12 + r * math.cos(a + da), 12 + r * math.sin(a + da)))
    return "M" + " L".join(f"{x:.2f} {y:.2f}" for x, y in pts) + " Z"


