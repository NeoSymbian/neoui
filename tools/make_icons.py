def shapes(name: str, colour: str) -> str:
    out = []
    for kind, data in GLYPHS[name]:
        if kind == "p":
            out.append(f'<path d="{data}" fill="none" stroke="{colour}"/>')
        elif kind == "f":
            out.append(f'<path d="{data}" fill="{colour}" stroke="none"/>')
        elif kind == "c":
            cx, cy, r = data
            out.append(
                f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="{colour}"/>'
            )
        else:
            cx, cy, r = data
            out.append(
                f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="{colour}" stroke="none"/>'
            )
    return "".join(out)


def mix(hex_colour: str, other: tuple, t: float) -> str:
    c = [int(hex_colour[i : i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(
        f"{round(a + (b - a) * t):02x}" for a, b in zip(c, other, strict=True)
    )


def sys_svg(name: str) -> str:
    return (
        HEAD
        + '<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="0 0 24 24">'
        f'<g stroke-width="{STROKE}" stroke-linecap="round" stroke-linejoin="round">{shapes(name, "#ffffff")}</g></svg>\n'
    )


def app_svg(name: str, base: str) -> str:
    top, bottom = mix(base, (255, 255, 255), 0.22), mix(base, (0, 0, 0), 0.12)
    # 96-unit tile, corner radius 26 (a soft squircle), the 24-grid glyph scaled to 52 units and centred
    s = 52 / 24
    return (
        HEAD
        + '<svg xmlns="http://www.w3.org/2000/svg" width="192" height="192" viewBox="0 0 96 96">'
        f'<defs><linearGradient id="t" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{top}"/>'
        f'<stop offset="1" stop-color="{bottom}"/></linearGradient></defs>'
        '<rect x="2" y="2" width="92" height="92" rx="26" fill="url(#t)"/>'
        '<rect x="2.75" y="2.75" width="90.5" height="90.5" rx="25.25" fill="none" stroke="#ffffff" stroke-opacity="0.18" stroke-width="1.5"/>'
        f'<g transform="translate({48 - 12 * s:.3f} {48 - 12 * s:.3f}) scale({s:.4f})" stroke-width="{STROKE}" '
        f'stroke-linecap="round" stroke-linejoin="round">{shapes(name, "#ffffff")}</g></svg>\n'
    )


def main() -> None:
    for sub in ("sys", "apps"):
        os.makedirs(os.path.join(OUT, sub), exist_ok=True)
    for name in GLYPHS:
        if name in APPS:
            continue
        with open(os.path.join(OUT, "sys", name + ".svg"), "w") as f:
            f.write(sys_svg(name))
    for name, base in APPS.items():
        with open(os.path.join(OUT, "apps", name + ".svg"), "w") as f:
            f.write(app_svg(name, base))
    print(
        f"make_icons: {len(APPS)} app icons, {len(GLYPHS) - len(APPS)} system icons -> {os.path.normpath(OUT)}"
    )


if __name__ == "__main__":
    main()
